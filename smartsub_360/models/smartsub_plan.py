# -*- coding: utf-8 -*-
from odoo import api, fields, models, _
from odoo.exceptions import ValidationError


class SmartsubPlan(models.Model):
    _name = 'smartsub.plan'
    _description = 'Subscription Plan'
    _order = 'name asc'

    name = fields.Char(
        string="Plan Name",
        required=True,
        translate=True,
        help="Display name of the subscription plan.",
    )
    code = fields.Char(
        string="Plan Code",
        index=True,
        help="Internal reference or SKU code for this plan.",
    )
    active = fields.Boolean(
        string="Active",
        default=True,
        help="If unchecked, allows hiding the plan without removing it.",
    )
    company_id = fields.Many2one(
        comodel_name='res.company',
        string="Company",
        required=True,
        default=lambda self: self.env.company,
    )
    currency_id = fields.Many2one(
        comodel_name='res.currency',
        string="Currency",
        compute='_compute_currency_id',
        store=True,
        readonly=False,
        precompute=True,
        help="Billing currency for recurring charges.",
    )
    billing_interval = fields.Selection(
        selection=[
            ('daily', 'Daily'),
            ('weekly', 'Weekly'),
            ('monthly', 'Monthly'),
            ('yearly', 'Yearly'),
        ],
        string="Billing Interval",
        default='monthly',
        required=True,
        help="Time unit for recurring billing frequency.",
    )
    interval_count = fields.Integer(
        string="Interval Count",
        default=1,
        required=True,
        help="Multiplier for the billing interval (e.g. 1 Month, 3 Months).",
    )
    product_id = fields.Many2one(
        comodel_name='product.product',
        string="Recurring Product",
        domain="[('is_subscription', '=', True)]",
        required=True,
        help="The product item added to customer invoices generated by this plan.",
    )
    price = fields.Monetary(
        string="Recurring Price",
        currency_field='currency_id',
        required=True,
        help="Default recurring price charged each billing cycle.",
    )
    trial_period_days = fields.Integer(
        string="Trial Period (Days)",
        default=0,
        help="Grace period before the first recurring invoice is generated.",
    )
    auto_close_unpaid_days = fields.Integer(
        string="Auto-Close Unpaid (Days)",
        default=15,
        help="Days after due date before overdue contracts are marked closed or paused.",
    )
    contract_ids = fields.One2many(
        comodel_name='smartsub.contract',
        inverse_name='plan_id',
        string="Contracts",
    )
    contract_count = fields.Integer(
        string="Contract Count",
        compute='_compute_contract_count',
    )

    @api.depends('company_id')
    def _compute_currency_id(self):
        for plan in self:
            plan.currency_id = plan.company_id.currency_id

    @api.depends('contract_ids')
    def _compute_contract_count(self):
        for plan in self:
            plan.contract_count = len(plan.contract_ids)

    @api.constrains('interval_count')
    def _check_interval_count(self):
        for plan in self:
            if plan.interval_count <= 0:
                raise ValidationError(_("Interval count must be strictly greater than 0."))

    @api.constrains('price')
    def _check_price(self):
        for plan in self:
            if plan.price < 0.0:
                raise ValidationError(_("Recurring price cannot be negative."))

    @api.constrains('trial_period_days', 'auto_close_unpaid_days')
    def _check_grace_periods(self):
        for plan in self:
            if plan.trial_period_days < 0:
                raise ValidationError(_("Trial period days cannot be negative."))
            if plan.auto_close_unpaid_days < 0:
                raise ValidationError(_("Auto-close unpaid days cannot be negative."))
